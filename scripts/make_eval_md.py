"""Generate eval_P2_<TeamID>.md from results/*.json (never type numbers by hand).

Line 1 = USNs, comma-separated (required by the instruction sheet). Metric
order follows the problem statement: PSNR & SSIM, Delta E, LPIPS, parameters &
model size, inference latency & memory.

  python -m scripts.make_eval_md --team T15 --usns 1XX22CS001,1XX22CS002,1XX22CS003,1XX22CS004
"""
from __future__ import annotations

import argparse
import json
import os

PROTOCOL_TITLES = {
    "sidd_raw": "SIDD RAW -> sRGB, held-out camera (unseen sensor)",
    "sidd_srgb": "SIDD validation sRGB blocks (restoration stage, standard benchmark)",
    "synthetic": "Unseen content: clean photos -> simulated phone RAW at 3 noise levels",
}


def load(path):
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return None


def fmt(v, nd=2):
    return "-" if v is None else f"{v:.{nd}f}"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--team", required=True)
    p.add_argument("--usns", required=True, help="comma-separated USNs")
    p.add_argument("--results", default="results")
    a = p.parse_args()
    usns = ",".join(u.strip() for u in a.usns.split(","))
    L = [usns, "", f"# Evaluation - Problem P2 (Hybrid learned smartphone ISP) - Team {a.team}", "",
         "All numbers below are generated by `scripts/make_eval_md.py` from `results/*.json`, which are written by "
         "`scripts/evaluate.py`, `scripts/benchmark.py` and `scripts/robustness.py`.", ""]

    evals = {k: load(os.path.join(a.results, f"eval_{k}.json")) for k in PROTOCOL_TITLES}
    # 1-3: quality metrics, one table per protocol (PSNR, SSIM, Delta E, LPIPS in the required order)
    L += ["## 1. PSNR and SSIM  /  2. Colour accuracy (Delta E 2000)  /  3. LPIPS", ""]
    for k, title in PROTOCOL_TITLES.items():
        e = evals[k]
        L.append(f"### {title}")
        if not e:
            L += ["", "_not run_", ""]
            continue
        n = next(iter(e["summary"].values()))["n"]
        L += ["", f"Device: {e.get('torch_gpu') or e['device']} - images: {n}", "",
              "| Variant | PSNR (dB) ^ | SSIM ^ | Delta E 2000 v | LPIPS v | Latency / image (s) |",
              "|---|---|---|---|---|---|"]
        for name, s in e["summary"].items():
            L.append(f"| {name} | {fmt(s['psnr'])} | {fmt(s['ssim'], 4)} | {fmt(s['delta_e'], 3)} | "
                     f"{fmt(s.get('lpips'), 4)} | {fmt(s['latency_s'], 3)} |")
        L.append("")

    # 4-5: efficiency
    b = load(os.path.join(a.results, "benchmark.json"))
    L += ["## 4. Model parameters and model size  /  5. Inference latency and memory consumption", ""]
    if b:
        L += [f"Input: {b['size']}x{b['size']} ({b['size'] ** 2 / 1e6:.2f} MP). Median of repeated runs after warm-up.", "",
              "| Variant | Params (M) | Size (MB) | Latency median (ms) | Latency p90 (ms) | Peak RAM (MB) | Peak GPU mem (MB) | Device |",
              "|---|---|---|---|---|---|---|---|"]
        for r in b["results"]:
            L.append(f"| {r['name']} | {fmt(r.get('params_M'), 3)} | {fmt(r.get('size_MB'))} | {fmt(r['latency_ms_median'], 1)} | "
                     f"{fmt(r['latency_ms_p90'], 1)} | {fmt(r['peak_rss_MB'], 0)} | {fmt(r.get('gpu_peak_MB'), 0)} | {r.get('device', '')} |")
    else:
        L.append("_not run_")
    L.append("")

    rb = load(os.path.join(a.results, "robustness.json"))
    L += ["## Robustness under challenging conditions (PSNR dB / Delta E)", ""]
    if rb:
        names = list(next(iter(rb.values())).keys())
        L += ["| Condition | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
        for c, cd in rb.items():
            L.append(f"| {c} | " + " | ".join(f"{cd[n]['psnr']:.2f} / {cd[n]['delta_e']:.2f}" for n in names) + " |")
        L += ["", "![robustness](results/robustness.png)"]
    else:
        L.append("_not run_")
    L += ["", "## Ablations", "",
          "Rows prefixed `abl_` in the tables above are separately trained or configured ablations: "
          "`abl_*no_noise_map` (teacher fine-tuned identically but without the noise-map input), "
          "`abl_*student_no_distillation` (student trained on ground truth only), "
          "`abl_F_random_routing_balanced` (router replaced by random tile assignment at the same compute budget). `D0_*` is the pretrained NAFNet before our fine-tuning; `E_student_fp32` vs "
          "`E_student_int8` isolates quantisation; `C_*` vs `D_*` compares denoise-before vs denoise-after rendering.",
          "", "Failure cases and their causes: see `docs/ablation_and_failures.md`.", ""]
    out = f"eval_P2_{a.team}.md"
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
